/*
  Emissor NF-e / NFC-e - estrutura do banco (Firebird 3.0 ou superior)

  Aplicado automaticamente pelo sistema na abertura (Infra.Migracao), que grava
  o nome do script na tabela SCHEMA_VERSAO. Script já aplicado não roda de novo:
  alteração no banco vai sempre num script novo, com o próximo número.
*/

CREATE TABLE EMITENTE (
  ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  RAZAO_SOCIAL        VARCHAR(60) NOT NULL,
  NOME_FANTASIA       VARCHAR(60),
  CNPJ                VARCHAR(14) NOT NULL,
  IE                  VARCHAR(14) NOT NULL,
  CRT                 SMALLINT DEFAULT 1 NOT NULL,
  LOGRADOURO          VARCHAR(60),
  NUMERO              VARCHAR(60),
  COMPLEMENTO         VARCHAR(60),
  BAIRRO              VARCHAR(60),
  CODIGO_MUNICIPIO    INTEGER,
  MUNICIPIO           VARCHAR(60),
  UF                  CHAR(2),
  CEP                 VARCHAR(8),
  TELEFONE            VARCHAR(14),
  EMAIL               VARCHAR(100),
  SERIE_NFE           SMALLINT DEFAULT 1 NOT NULL,
  PROXIMO_NUMERO_NFE  INTEGER DEFAULT 1 NOT NULL,
  SERIE_NFCE          SMALLINT DEFAULT 1 NOT NULL,
  PROXIMO_NUMERO_NFCE INTEGER DEFAULT 1 NOT NULL,
  CONSTRAINT PK_EMITENTE PRIMARY KEY (ID),
  CONSTRAINT CK_EMITENTE_CRT CHECK (CRT IN (1, 2, 3))
);

CREATE TABLE CLIENTE (
  ID                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOME              VARCHAR(60) NOT NULL,
  CPF_CNPJ          VARCHAR(14),
  IE                VARCHAR(14),
  INDICADOR_IE      SMALLINT DEFAULT 9 NOT NULL,
  EMAIL             VARCHAR(100),
  TELEFONE          VARCHAR(14),
  LOGRADOURO        VARCHAR(60),
  NUMERO            VARCHAR(60),
  COMPLEMENTO       VARCHAR(60),
  BAIRRO            VARCHAR(60),
  CODIGO_MUNICIPIO  INTEGER,
  MUNICIPIO         VARCHAR(60),
  UF                CHAR(2),
  CEP               VARCHAR(8),
  ATIVO             BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (ID),
  CONSTRAINT CK_CLIENTE_INDICADOR_IE CHECK (INDICADOR_IE IN (1, 2, 9))
);

CREATE INDEX IX_CLIENTE_NOME ON CLIENTE (NOME);
CREATE INDEX IX_CLIENTE_CPF_CNPJ ON CLIENTE (CPF_CNPJ);

CREATE TABLE PRODUTO (
  ID                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  CODIGO            VARCHAR(60) NOT NULL,
  DESCRICAO         VARCHAR(120) NOT NULL,
  EAN               VARCHAR(14) DEFAULT 'SEM GTIN' NOT NULL,
  NCM               VARCHAR(8) NOT NULL,
  CEST              VARCHAR(7),
  CFOP              VARCHAR(4) NOT NULL,
  UNIDADE           VARCHAR(6) NOT NULL,
  PRECO             NUMERIC(15,4) DEFAULT 0 NOT NULL,
  ORIGEM            SMALLINT DEFAULT 0 NOT NULL,
  CST_CSOSN         VARCHAR(3) NOT NULL,
  ALIQUOTA_ICMS     NUMERIC(5,2) DEFAULT 0 NOT NULL,
  REDUCAO_BC_ICMS   NUMERIC(5,2) DEFAULT 0 NOT NULL,
  CST_PIS           VARCHAR(2) DEFAULT '49' NOT NULL,
  ALIQUOTA_PIS      NUMERIC(5,2) DEFAULT 0 NOT NULL,
  CST_COFINS        VARCHAR(2) DEFAULT '49' NOT NULL,
  ALIQUOTA_COFINS   NUMERIC(5,2) DEFAULT 0 NOT NULL,
  ATIVO             BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_PRODUTO PRIMARY KEY (ID),
  CONSTRAINT UK_PRODUTO_CODIGO UNIQUE (CODIGO),
  CONSTRAINT CK_PRODUTO_ORIGEM CHECK (ORIGEM BETWEEN 0 AND 8)
);

CREATE INDEX IX_PRODUTO_DESCRICAO ON PRODUTO (DESCRICAO);

/* CODIGO_SEFAZ = tPag da NF-e (01 dinheiro, 03 cartão de crédito, 17 PIX...) */
CREATE TABLE FORMA_PAGAMENTO (
  ID            INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  DESCRICAO     VARCHAR(60) NOT NULL,
  CODIGO_SEFAZ  VARCHAR(2) NOT NULL,
  ATIVO         BOOLEAN DEFAULT TRUE NOT NULL,
  CONSTRAINT PK_FORMA_PAGAMENTO PRIMARY KEY (ID)
);

/*
  STATUS: 0 digitação, 1 autorizada, 2 rejeitada, 3 denegada,
          4 cancelada, 5 contingência (NFC-e offline pendente de envio)
  NUMERO fica nulo até a nota ser numerada na primeira transmissão.
*/
CREATE TABLE NOTA (
  ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  MODELO              SMALLINT NOT NULL,
  SERIE               SMALLINT NOT NULL,
  NUMERO              INTEGER,
  DATA_EMISSAO        TIMESTAMP NOT NULL,
  NATUREZA_OPERACAO   VARCHAR(60) NOT NULL,
  CLIENTE_ID          INTEGER,
  CPF_CONSUMIDOR      VARCHAR(14),
  STATUS              SMALLINT DEFAULT 0 NOT NULL,
  CONTINGENCIA        BOOLEAN DEFAULT FALSE NOT NULL,
  CHAVE               VARCHAR(44),
  PROTOCOLO           VARCHAR(20),
  CSTAT               SMALLINT,
  MOTIVO              VARCHAR(255),
  VALOR_PRODUTOS      NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_DESCONTO      NUMERIC(15,2) DEFAULT 0 NOT NULL,
  BASE_ICMS           NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_ICMS          NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_PIS           NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_COFINS        NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_TOTAL         NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_TROCO         NUMERIC(15,2) DEFAULT 0 NOT NULL,
  ARQUIVO_XML         VARCHAR(500),
  OBSERVACAO          VARCHAR(2000),
  CONSTRAINT PK_NOTA PRIMARY KEY (ID),
  CONSTRAINT FK_NOTA_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
  CONSTRAINT UK_NOTA_NUMERO UNIQUE (MODELO, SERIE, NUMERO),
  CONSTRAINT UK_NOTA_CHAVE UNIQUE (CHAVE),
  CONSTRAINT CK_NOTA_MODELO CHECK (MODELO IN (55, 65)),
  CONSTRAINT CK_NOTA_STATUS CHECK (STATUS BETWEEN 0 AND 5)
);

CREATE DESCENDING INDEX IX_NOTA_DATA ON NOTA (DATA_EMISSAO);

CREATE TABLE NOTA_ITEM (
  ID                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOTA_ID           INTEGER NOT NULL,
  NUMERO_ITEM       SMALLINT NOT NULL,
  PRODUTO_ID        INTEGER NOT NULL,
  CODIGO            VARCHAR(60) NOT NULL,
  DESCRICAO         VARCHAR(120) NOT NULL,
  EAN               VARCHAR(14) NOT NULL,
  NCM               VARCHAR(8) NOT NULL,
  CEST              VARCHAR(7),
  CFOP              VARCHAR(4) NOT NULL,
  UNIDADE           VARCHAR(6) NOT NULL,
  QUANTIDADE        NUMERIC(15,4) NOT NULL,
  VALOR_UNITARIO    NUMERIC(15,4) NOT NULL,
  VALOR_PRODUTO     NUMERIC(15,2) NOT NULL,
  VALOR_DESCONTO    NUMERIC(15,2) DEFAULT 0 NOT NULL,
  ORIGEM            SMALLINT NOT NULL,
  CST_CSOSN         VARCHAR(3) NOT NULL,
  ALIQUOTA_ICMS     NUMERIC(5,2) DEFAULT 0 NOT NULL,
  REDUCAO_BC_ICMS   NUMERIC(5,2) DEFAULT 0 NOT NULL,
  BASE_ICMS         NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_ICMS        NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CST_PIS           VARCHAR(2) NOT NULL,
  ALIQUOTA_PIS      NUMERIC(5,2) DEFAULT 0 NOT NULL,
  BASE_PIS          NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_PIS         NUMERIC(15,2) DEFAULT 0 NOT NULL,
  CST_COFINS        VARCHAR(2) NOT NULL,
  ALIQUOTA_COFINS   NUMERIC(5,2) DEFAULT 0 NOT NULL,
  BASE_COFINS       NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_COFINS      NUMERIC(15,2) DEFAULT 0 NOT NULL,
  VALOR_TOTAL       NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_NOTA_ITEM PRIMARY KEY (ID),
  CONSTRAINT FK_NOTA_ITEM_NOTA FOREIGN KEY (NOTA_ID) REFERENCES NOTA (ID) ON DELETE CASCADE,
  CONSTRAINT FK_NOTA_ITEM_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTO (ID),
  CONSTRAINT UK_NOTA_ITEM UNIQUE (NOTA_ID, NUMERO_ITEM)
);

CREATE TABLE NOTA_PAGAMENTO (
  ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOTA_ID             INTEGER NOT NULL,
  FORMA_PAGAMENTO_ID  INTEGER NOT NULL,
  CODIGO_SEFAZ        VARCHAR(2) NOT NULL,
  DESCRICAO           VARCHAR(60) NOT NULL,
  VALOR               NUMERIC(15,2) NOT NULL,
  CONSTRAINT PK_NOTA_PAGAMENTO PRIMARY KEY (ID),
  CONSTRAINT FK_NOTA_PAGAMENTO_NOTA FOREIGN KEY (NOTA_ID) REFERENCES NOTA (ID) ON DELETE CASCADE,
  CONSTRAINT FK_NOTA_PAGAMENTO_FORMA FOREIGN KEY (FORMA_PAGAMENTO_ID) REFERENCES FORMA_PAGAMENTO (ID)
);

/*
  Histórico de toda operação fiscal (emissão, cancelamento, CC-e, inutilização,
  contingência). Inutilização não tem nota, por isso NOTA_ID é opcional.
  TIPO: 0 emissão, 1 cancelamento, 2 carta de correção, 3 inutilização, 4 contingência
*/
CREATE TABLE NOTA_EVENTO (
  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  NOTA_ID         INTEGER,
  TIPO            SMALLINT NOT NULL,
  DATA_HORA       TIMESTAMP NOT NULL,
  SEQUENCIA       SMALLINT DEFAULT 1 NOT NULL,
  MODELO          SMALLINT,
  SERIE           SMALLINT,
  NUMERO_INICIAL  INTEGER,
  NUMERO_FINAL    INTEGER,
  CSTAT           SMALLINT,
  MOTIVO          VARCHAR(255),
  PROTOCOLO       VARCHAR(20),
  TEXTO           VARCHAR(1000),
  ARQUIVO_XML     VARCHAR(500),
  SUCESSO         BOOLEAN DEFAULT FALSE NOT NULL,
  CONSTRAINT PK_NOTA_EVENTO PRIMARY KEY (ID),
  CONSTRAINT FK_NOTA_EVENTO_NOTA FOREIGN KEY (NOTA_ID) REFERENCES NOTA (ID),
  CONSTRAINT CK_NOTA_EVENTO_TIPO CHECK (TIPO BETWEEN 0 AND 4)
);

CREATE INDEX IX_NOTA_EVENTO_NOTA ON NOTA_EVENTO (NOTA_ID);

COMMIT;
